import { describe, expect, it } from 'vitest';
import { getDrawDate, toKstIsoString } from './drawDate';

describe('getDrawDate', () => {
  it.each([
    ['월요일', '2026-10-19T12:00:00+09:00', '2026-10-24'],
    ['화요일', '2026-10-20T12:00:00+09:00', '2026-10-24'],
    ['수요일', '2026-10-21T12:00:00+09:00', '2026-10-24'],
    ['목요일', '2026-10-22T12:00:00+09:00', '2026-10-24'],
    ['금요일', '2026-10-23T23:59:59+09:00', '2026-10-24'],
    ['토요일 00:00', '2026-10-24T00:00:00+09:00', '2026-10-24'],
    ['토요일 23:59', '2026-10-24T23:59:59+09:00', '2026-10-24'],
    ['일요일 00:00', '2026-10-25T00:00:00+09:00', '2026-10-31'],
    ['일요일 00:05 (예약 실행 시각)', '2026-10-25T00:05:00+09:00', '2026-10-31'],
  ])('%s → 다가오는 토요일', (_, at, expected) => {
    expect(getDrawDate(new Date(at))).toBe(expected);
  });

  it('UTC로는 토요일이지만 KST로는 일요일인 시각은 다음 주 토요일이다', () => {
    // 2026-10-24(토) 15:05 UTC = 2026-10-25(일) 00:05 KST
    expect(getDrawDate(new Date('2026-10-24T15:05:00Z'))).toBe('2026-10-31');
  });

  it('UTC로는 금요일이지만 KST로는 토요일인 시각은 당일이다', () => {
    // 2026-10-23(금) 15:00 UTC = 2026-10-24(토) 00:00 KST
    expect(getDrawDate(new Date('2026-10-23T15:00:00Z'))).toBe('2026-10-24');
  });

  it('월·연도가 바뀌는 경우도 처리한다', () => {
    expect(getDrawDate(new Date('2026-10-26T09:00:00+09:00'))).toBe('2026-10-31');
    expect(getDrawDate(new Date('2026-11-01T09:00:00+09:00'))).toBe('2026-11-07');
    expect(getDrawDate(new Date('2026-12-27T00:05:00+09:00'))).toBe('2027-01-02');
  });
});

describe('toKstIsoString', () => {
  it('KST 시각과 +09:00 오프셋으로 표시한다', () => {
    expect(toKstIsoString(new Date('2026-10-24T15:05:00Z'))).toBe('2026-10-25T00:05:00+09:00');
    expect(toKstIsoString(new Date('2026-12-31T15:00:00Z'))).toBe('2027-01-01T00:00:00+09:00');
  });
});
